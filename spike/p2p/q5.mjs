// Q5: host tab A runs the worker clock + relays to a peer in another window; A is hidden by opening a tab over it.
import { spawn } from "node:child_process";
const HIDDEN_MS = Number(process.argv[2] ?? 7 * 60000);
const port = 9334;
const chrome = spawn(process.env.VIBEWARS_CHROMIUM, [`--user-data-dir=/tmp/q5-prof-${Date.now()}`, `--remote-debugging-port=${port}`, "--no-first-run", "--no-default-browser-check", "about:blank"], { env: { ...process.env, DISPLAY: ":97" }, stdio: "ignore" });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await sleep(3000);
const base = `http://127.0.0.1:${port}`;
let nextId = 1;
async function session(wsUrl) {
  const ws = new WebSocket(wsUrl);
  await new Promise((r) => (ws.onopen = r));
  const pending = new Map();
  ws.onmessage = (m) => { const d = JSON.parse(m.data); pending.get(d.id)?.(d); pending.delete(d.id); };
  const send = (method, params = {}) => new Promise((r) => { const id = nextId++; pending.set(id, r); ws.send(JSON.stringify({ id, method, params })); });
  const evalJs = async (expr) => (await send("Runtime.evaluate", { expression: expr, awaitPromise: true, returnByValue: true })).result?.result?.value;
  return { send, evalJs, close: () => ws.close() };
}
const URL_ = "http://127.0.0.1:26431/index.html";
const tabs = await (await fetch(`${base}/json/list`)).json();
const a = await session(tabs.find((t) => t.type === "page").webSocketDebuggerUrl);
await a.send("Page.navigate", { url: URL_ });
await sleep(1500);
const browserWs = (await (await fetch(`${base}/json/version`)).json()).webSocketDebuggerUrl;
const br = await session(browserWs);
const { result: { targetId } } = await br.send("Target.createTarget", { url: URL_, newWindow: true });
await sleep(1500);
const bInfo = (await (await fetch(`${base}/json/list`)).json()).find((t) => t.id === targetId);
const b = await session(bInfo.webSocketDebuggerUrl);
const room = `spike-q5-${Date.now()}`;
const hostId = await a.evalJs(`spike.joinTrystero({ appId: "vibewars-spike-16", roomId: "${room}", password: "pw" })`);
await b.evalJs(`spike.joinTrystero({ appId: "vibewars-spike-16", roomId: "${room}", password: "pw" })`);
for (let i = 0; i < 300 && (await a.evalJs("spike.peers().length")) < 1; i++) await sleep(200);
console.log("connected; host", hostId);
await a.evalJs("spike.workerHost(2048)");
await sleep(60000);
const visibleFrom = await a.evalJs("spike.now()") - 60000;
await fetch(`${base}/json/new?about:blank`, { method: "PUT" });
await sleep(1000);
console.log("A visibility now:", await a.evalJs("document.visibilityState"), "B:", await b.evalJs("document.visibilityState"));
const hiddenFrom = await a.evalJs("spike.now()");
await sleep(HIDDEN_MS);
console.log("visible minute, per second:", JSON.stringify(await a.evalJs(`spike.tickRates(${visibleFrom})`)).slice(0, 200));
console.log("hidden, ticks/s per minute:", JSON.stringify(await a.evalJs(`spike.tickRates(${hiddenFrom})`)));
console.log("peer B arrivals/s per minute since hidden:", JSON.stringify(await b.evalJs(`spike.arrivalRates(${hiddenFrom})`)));
console.log("peer B stats:", JSON.stringify(await b.evalJs("spike.recvStats()")));
console.log("A visibility at end:", await a.evalJs("document.visibilityState"));
chrome.kill();
process.exit(0);
