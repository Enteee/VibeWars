/**
 * One `OwnSkillModifier` (#1761): the skills `filter` names, and what it
 * changes about them; every knob it leaves out changes nothing.
 */
export function ownSkills(
  filter: Partial<OwnSkillFilter>,
  change: Partial<Omit<OwnSkillModifier, "filter">>,
): OwnSkillModifier {
  return {
    filter: {
      type: undefined,
      attributeId: undefined,
      profession: undefined,
      chainRoles: undefined,
      weapon: undefined,
      targetsFoe: false,
      ...filter,
    },
    energyBase: undefined,
    energyDiscount: 0,
    energyFloor: 1,
    energySurcharge: 0,
    activationMultiplier: 1,
    activationSecondsLess: 0,
    rechargeFaster: 0,
    rechargeSlower: 0,
    durationMultiplier: 1,
    healMultiplier: 1,
    sparesDivineFavor: false,
    notEasilyInterrupted: false,
    overcastPerUse: 0,
    uses: undefined,
    ...change,
  };
}
